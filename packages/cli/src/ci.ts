import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

import { VERSION } from './env';

export type CiProvider = 'github' | 'gitlab';

const pkg = `fortis-watchdog@${VERSION}`;

/**
 * GitHub Actions: a full scan on every pull request and push (results as PR annotations and,
 * where code scanning is available, as SARIF alerts), and a ZAP test of staging after each
 * push to the staging branch, once the new deploy is answering.
 */
export function githubWorkflow(opts: { stagingBranch: string; target?: string }) {
  const target = opts.target ?? '${{ vars.FORTIS_STAGING_URL }}';
  return `# Generated by \`fortis ci init\`. Edit freely.
# Secrets:   FORTIS_KEY (Settings → Secrets and variables → Actions)
#            FORTIS_TEST_TOKEN (optional: a staging test user's token, for logged-in tests)
# Variables: FORTIS_STAGING_URL (the staging URL verified in the Fortis dashboard)
name: Fortis

on:
  pull_request:
  push:
    branches: [main, master, dev, ${opts.stagingBranch}]
  workflow_dispatch:

permissions:
  contents: read
  security-events: write

concurrency:
  group: fortis-\${{ github.ref }}
  cancel-in-progress: true

jobs:
  scan:
    name: Code scan
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 22
      - name: Fortis scan
        run: npx --yes ${pkg} scan --ci --sarif fortis.sarif
        env:
          FORTIS_KEY: \${{ secrets.FORTIS_KEY }}
      - name: Upload to GitHub code scanning
        if: always() && hashFiles('fortis.sarif') != ''
        # Code scanning is free on public repositories and needs GitHub Advanced Security on private ones.
        continue-on-error: true
        uses: github/codeql-action/upload-sarif@v3
        with:
          sarif_file: fortis.sarif
          category: fortis

  staging:
    name: Staging test (ZAP)
    needs: scan
    if: github.event_name == 'workflow_dispatch' || (github.event_name == 'push' && github.ref == 'refs/heads/${opts.stagingBranch}')
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 22
      - name: Fortis test
        # --wait gives the new deploy time to come up before testing.
        run: npx --yes ${pkg} test --target ${target} --wait 600
        env:
          FORTIS_KEY: \${{ secrets.FORTIS_KEY }}
          FORTIS_ZAP_AUTH: \${{ secrets.FORTIS_TEST_TOKEN }}
`;
}

export function gitlabJobs(opts: { stagingBranch: string; target?: string }) {
  const target = opts.target ?? '$FORTIS_STAGING_URL';
  return `# Generated by \`fortis ci init\`. Add to .gitlab-ci.yml with:
#   include:
#     - local: fortis.gitlab-ci.yml
# CI/CD variables: FORTIS_KEY (masked), FORTIS_STAGING_URL, FORTIS_TEST_TOKEN (optional, masked)

fortis-scan:
  stage: test
  image: node:22
  script:
    - npx --yes ${pkg} scan --ci --sarif fortis.sarif
  artifacts:
    when: always
    paths: [fortis.sarif]
  rules:
    - if: $CI_PIPELINE_SOURCE == "merge_request_event"
    - if: $CI_COMMIT_BRANCH

fortis-staging:
  stage: test
  needs: [fortis-scan]
  image: node:22
  services:
    - docker:27-dind
  variables:
    DOCKER_HOST: tcp://docker:2375
    DOCKER_TLS_CERTDIR: ""
    FORTIS_ZAP_AUTH: $FORTIS_TEST_TOKEN
  before_script:
    - apt-get update -qq && apt-get install -y -qq docker.io > /dev/null
  script:
    - npx --yes ${pkg} test --target ${target} --wait 600
  rules:
    - if: $CI_COMMIT_BRANCH == "${opts.stagingBranch}"
`;
}

export function writeCi(root: string, provider: CiProvider, opts: { stagingBranch: string; target?: string; force?: boolean }) {
  const rel = provider === 'github' ? '.github/workflows/fortis.yml' : 'fortis.gitlab-ci.yml';
  const abs = join(root, rel);
  if (existsSync(abs) && !opts.force) return { path: rel, written: false };
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, provider === 'github' ? githubWorkflow(opts) : gitlabJobs(opts));
  return { path: rel, written: true };
}

export function detectProvider(root: string): CiProvider {
  if (existsSync(join(root, '.gitlab-ci.yml'))) return 'gitlab';
  return 'github';
}
