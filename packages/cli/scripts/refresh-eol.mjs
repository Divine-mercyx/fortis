// Refreshes the end-of-life table the Dockerfile rules use, from endoflife.date. The release workflow
// runs this before building, so each release carries current dates; commit the result now and then.
//   node scripts/refresh-eol.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** endoflife.date product, and the base images built on it. */
const PRODUCTS = {
  nodejs: ['node'],
  python: ['python'],
  debian: ['debian'],
  ubuntu: ['ubuntu'],
  'alpine-linux': ['alpine'],
  go: ['golang'],
  php: ['php'],
  ruby: ['ruby'],
  dotnet: ['mcr.microsoft.com/dotnet/aspnet', 'mcr.microsoft.com/dotnet/runtime', 'mcr.microsoft.com/dotnet/sdk', 'mcr.microsoft.com/dotnet/runtime-deps'],
};

const out = {};
for (const product of Object.keys(PRODUCTS)) {
  const res = await fetch(`https://endoflife.date/api/${product}.json`, { headers: { 'user-agent': 'fortis-release' } });
  if (!res.ok) throw new Error(`endoflife.date answered ${res.status} for ${product}`);
  const cycles = await res.json();
  // [cycle, end of life (or null while supported), codename]. "eol" is the end of security fixes.
  out[product] = cycles.map((c) => {
    const row = [String(c.cycle), typeof c.eol === 'string' ? c.eol : null];
    if (c.codename) row.push(String(c.codename).split(/\s+/)[0].toLowerCase());
    return row;
  });
}

const file = fileURLToPath(new URL('../src/rules/eol-data.ts', import.meta.url));
const body = Object.entries(out)
  .map(([product, rows]) => `  ${JSON.stringify(product)}: [\n${rows.map((r) => `    ${JSON.stringify(r)},`).join('\n')}\n  ],`)
  .join('\n');
writeFileSync(
  file,
  `// Generated by scripts/refresh-eol.mjs from endoflife.date on ${new Date().toISOString().slice(0, 10)}. Don't edit by hand.\n` +
    `// Each product: [release cycle, end of security support (null while supported), codename].\n\n` +
    `export const EOL_IMAGES: Record<string, string[]> = ${JSON.stringify(PRODUCTS, null, 2)};\n\n` +
    `export const EOL: Record<string, [string, string | null, string?][]> = {\n${body}\n};\n`,
);
console.log(`wrote ${file}`);
